"""Generate src/xml_encodings.rs: how Python's ElementTree (expat plus Python's codecs)
treats each encoding name an XML declaration can give.

Run it with Python 3.14 on Linux or macOS. On Windows, Python 3.14 can also reach the
code pages Windows itself provides, which CrowdWatch does not copy.

    python -W ignore scripts/gen_xml_encodings.py src/xml_encodings.rs
"""
import encodings, encodings.aliases, pkgutil, sys
import xml.etree.ElementTree as ET

modules = sorted(m.name for m in pkgutil.iter_modules(encodings.__path__) if m.name != "aliases")
aliases = sorted(encodings.aliases.aliases.items())

def outcome(name):
    doc = f'<?xml version="1.0" encoding="{name}"?><a/>'.encode()
    try:
        ET.fromstring(doc)
    except ET.ParseError as exc:
        if "unknown encoding" in str(exc):
            return ("Rejected", None)
        return ("Malformed", None)
    except ValueError as exc:
        if type(exc) is UnicodeError:
            return ("Undefined", None)
        assert "multi-byte" in str(exc), (name, exc)
        return ("MultiByte", None)
    except LookupError:
        return ("Lookup", None)
    table = bytes(range(256)).decode(name, "replace")
    assert len(table) == 256
    return ("Table", table)

def rust_str(chars):
    out = []
    for c in chars:
        cp = ord(c)
        if c == '"':
            out.append('\\"')
        elif c == '\\':
            out.append('\\\\')
        elif 0x20 <= cp < 0x7f:
            out.append(c)
        elif cp >= 0xa0 and c.isprintable() and cp != 0xfffd:
            out.append(c)
        else:
            out.append("\\u{%x}" % cp)
    return '"' + "".join(out) + '"'

tables = []
module_rows = []
for name in modules:
    if not name[:1].isalpha():
        # No declaration reaches it: an XML encoding name starts with a letter, and
        # Python's name normalising never makes a leading underscore (_win_cp_codecs).
        continue
    kind, table = outcome(name)
    if kind == "Table":
        low = [i for i in range(128) if table[i] != chr(i)]
        assert all(table[i] == "�" for i in low), (name, low)
        key = (table[128:], tuple(low))
        if key not in tables:
            tables.append(key)
        module_rows.append((name, f"Codec::Table({tables.index(key)})"))
    elif kind == "Malformed":
        sys.exit(f"module name {name} is not a valid encoding name")
    else:
        module_rows.append((name, f"Codec::{kind}"))

lines = []
lines.append("// Copyright (C) 2026 whispr.dev")
lines.append("// SPDX-License-Identifier: GPL-3.0-only")
lines.append("")
lines.append("//! Generated by scripts/gen_xml_encodings.py from Python's codecs and expat; do not edit.")
lines.append("//!")
lines.append("//! How Python's ElementTree treats an encoding named in an XML declaration that expat does")
lines.append("//! not know itself: Python decodes the 256 byte values with that codec, and expat accepts")
lines.append("//! the result as a single-byte table, or the codec is refused.")
lines.append("")
lines.append("/// What a Python codec name leads to.")
lines.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
lines.append("pub enum Codec {")
lines.append("    /// A single-byte table expat accepts: `TABLES[n]`.")
lines.append("    Table(usize),")
lines.append("    /// A single-byte table expat refuses (ParseError: unknown encoding).")
lines.append("    Rejected,")
lines.append("    /// A multi-byte codec (ValueError: multi-byte encodings are not supported).")
lines.append("    MultiByte,")
lines.append("    /// Not a text encoding (LookupError).")
lines.append("    Lookup,")
lines.append("    /// The `undefined` codec (UnicodeError).")
lines.append("    Undefined,")
lines.append("}")
lines.append("")
lines.append("/// A single-byte table: the characters for bytes 0x80 to 0xFF (U+FFFD marks a byte that")
lines.append("/// is not allowed) and the ASCII bytes the codec does not allow.")
lines.append("pub struct Table {")
lines.append("    pub high: &'static str,")
lines.append("    pub low_invalid: &'static [u8],")
lines.append("}")
lines.append("")
lines.append(f"pub const ALIASES: [(&str, &str); {len(aliases)}] = [")
for k, v in aliases:
    lines.append(f'    ("{k}", "{v}"),')
lines.append("];")
lines.append("")
lines.append(f"pub const MODULES: [(&str, Codec); {len(module_rows)}] = [")
for k, v in module_rows:
    lines.append(f'    ("{k}", {v}),')
lines.append("];")
lines.append("")
lines.append(f"pub const TABLES: [Table; {len(tables)}] = [")
for high, low in tables:
    assert len(high) == 128
    lines.append("    Table {")
    lines.append(f"        high: {rust_str(high)},")
    lines.append(f"        low_invalid: &{list(low)},")
    lines.append("    },")
lines.append("];")
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print(len(aliases), "aliases,", len(module_rows), "modules,", len(tables), "tables")
assert aliases == sorted(aliases) and [m for m, _ in module_rows] == sorted(m for m, _ in module_rows)
