"""Generate src/unicode_tables.rs: the character classes behind Python's str methods
(isalnum, isprintable, isspace, isdigit) and the decimal digits int() and float() read.

CrowdWatch 0.1.0 ran on Python 3.14, whose character database is Unicode 16.0.0. This
script uses unicodedata2 when it is installed (pip install unicodedata2==16.0.0), and
Python's own unicodedata otherwise, and applies CPython's own definitions
(Tools/unicode/makeunicodedata.py) to every code point.

    python scripts/gen_unicode.py src/unicode_tables.rs
"""
import sys

try:
    import unicodedata2 as ud
except ImportError:
    import unicodedata as ud

LETTERS = {"Lu", "Ll", "Lt", "Lm", "Lo"}


def code_points():
    for cp in range(0x110000):
        if not 0xD800 <= cp <= 0xDFFF:
            yield cp


def alnum(ch):
    return (ud.category(ch) in LETTERS or ud.decimal(ch, None) is not None
            or ud.digit(ch, None) is not None or ud.numeric(ch, None) is not None)


def printable(ch):
    return ch == " " or ud.category(ch)[0] not in "CZ"


def space(ch):
    return ud.bidirectional(ch) in ("WS", "B", "S") or ud.category(ch) == "Zs"


def digit(ch):
    return ud.digit(ch, None) is not None


def ranges(predicate, include_surrogates=False):
    out, start = [], None
    for cp in range(0x110000):
        surrogate = 0xD800 <= cp <= 0xDFFF
        ok = include_surrogates if surrogate else predicate(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, doc, items):
    lines = [f"/// {doc}", "#[rustfmt::skip]", f"pub(crate) static {name}: &[(u32, u32)] = &["]
    lines += [f"    (0x{a:04X}, 0x{b:04X})," for a, b in items]
    lines.append("];")
    return "\n".join(lines)


def main():
    zeros = [cp for cp in code_points() if ud.decimal(chr(cp), None) == 0]
    for cp in code_points():
        value = ud.decimal(chr(cp), None)
        assert value is None or cp - value in zeros, hex(cp)
    parts = [
        "// Copyright (C) 2026 whispr.dev",
        "// SPDX-License-Identifier: GPL-3.0-only",
        "",
        f"//! Unicode {ud.unidata_version} character classes for the Python string rules CrowdWatch",
        "//! relies on. Generated by scripts/gen_unicode.py; do not edit. Each table is sorted.",
        "",
        emit("ALNUM", "Code point ranges where Python's `str.isalnum()` is true.", ranges(alnum)),
        "",
        emit("UNPRINTABLE", "Code point ranges where Python's `str.isprintable()` is false.",
             ranges(lambda ch: not printable(ch), include_surrogates=True)),
        "",
        emit("SPACE", "Code point ranges where Python's `str.isspace()` is true.", ranges(space)),
        "",
        emit("DIGIT", "Code point ranges where Python's `str.isdigit()` is true.", ranges(digit)),
        "",
        "/// The zero of every run of ten decimal digits Python's `int()` and `float()` accept.",
        "#[rustfmt::skip]",
        "pub(crate) static DIGIT_ZEROS: &[u32] = &[",
        *[f"    0x{z:04X}," for z in zeros],
        "];",
        "",
    ]
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(parts))
    print(f"Unicode {ud.unidata_version}", file=sys.stderr)


if __name__ == "__main__":
    main()
